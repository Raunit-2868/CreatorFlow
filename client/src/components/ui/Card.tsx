  HTMLParagraphElement,
  React.HTMLAttributes<HTMLHeadingElement>
>(({ className, ...props }, ref) => (
  <h3
    ref={ref}
    className={cn('font-headline font-bold text-lg text-primary leading-tight', className)}
    {...props}
  />
));
CardTitle.displayName = 'CardTitle';

